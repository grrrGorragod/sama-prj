-- SAMA — table for cookie-encryption keys (needed when DataProtection__UseDatabase=true, e.g. on Render)
-- Supabase Dashboard → SQL Editor → New query → paste → Run. Safe to run more than once.
create table if not exists data_protection_keys (
  id            integer generated by default as identity primary key,
  friendly_name text,
  xml           text
);
-- only the backend (service/postgres role) should read this table
alter table data_protection_keys enable row level security;
